"""Package only completed full-duration results, code, and honest renderer provenance."""
import argparse
from pathlib import Path
import hashlib
import json
import zipfile
import shutil
import os

ROOT=Path(__file__).resolve().parents[1]


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--results',default='results/sumo_paper')
    parser.add_argument('--delivery',default='../output/SUMO_FULL_DURATION')
    a=parser.parse_args()
    results=Path(a.results).resolve();delivery=Path(a.delivery).resolve()
    marker=results/'FULL_STUDY_COMPLETE.json'
    if not marker.exists():raise SystemExit('Refusing to package an unfinished full study as completed results')
    status=json.loads(marker.read_text())
    if status.get('status')!='complete' or status.get('main_runs')!=450 or status.get('extended_runs')!=240:
        raise ValueError('Full-study completion marker does not match the requested protocol')
    delivery.mkdir(parents=True,exist_ok=True)
    payload=[]
    for folder in ('stg_ddqn','tools','configs','scripts','tests','matlab','docs'):
        payload.extend(p for p in (ROOT/folder).rglob('*') if p.is_file())
    for name in ('README.md','pyproject.toml','.gitignore','requirements.txt',
                 'requirements-sumo.txt','requirements-sumo-lock.txt'):
        payload.append(ROOT/name)
    # Full trace inputs and checksums are reproducible; multi-gigabyte CSVs and
    # internal resume pickles are deliberately not embedded in the code archive.
    for p in (ROOT/'data/sumo/paper').rglob('*'):
        if p.is_file() and p.name!='trace.csv' and p.suffix!='.log':payload.append(p)
    for p in results.rglob('*'):
        if not p.is_file():continue
        if '.trained_model_cache' in p.parts or '.resume.' in p.name:continue
        if p.name=='full_study_status.json':continue
        if p.suffix in ('.csv','.json','.md','.yaml','.txt') and '.lock' not in p.name:payload.append(p)
    training=results.with_name(results.name+'_training')
    payload.extend(p for p in training.glob('*') if p.suffix in ('.csv','.json'))
    checkpoint=ROOT/'checkpoints/sumo_stg_ddqn.pt'
    payload.extend([checkpoint,checkpoint.with_name(checkpoint.name+'.complete.json')])
    payload=sorted(set(p for p in payload if '__pycache__' not in p.parts and p.suffix!='.pyc'))
    checksum=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
    manifest=dict(status='complete',protocol=status,matlab='code supplied; MATLAB not executed on this host',
        renderer='Python/Matplotlib for included figures',
        included_file_sha256={str(p.relative_to(ROOT)):checksum(p) for p in payload},
        omitted='CSV mobility traces regenerated by stg_ddqn.sumo_scenario; internal resume states and extended model binaries omitted')
    (delivery/'FULL_DELIVERY_MANIFEST.json').write_text(json.dumps(manifest,indent=2)+'\n')
    archive=delivery/'SUMO_FULL_Python_MATLAB_Code_and_Results.zip'
    temporary=archive.with_suffix('.zip.partial')
    with zipfile.ZipFile(temporary,'w',zipfile.ZIP_DEFLATED,compresslevel=6) as z:
        prefix=Path('SUMO_FULL_IMPLEMENTATION')
        for p in payload:z.write(p,prefix/p.relative_to(ROOT))
        for p in (delivery/'plots_python').rglob('*'):
            if p.is_file():z.write(p,prefix/'plots/sumo_full_python'/p.relative_to(delivery/'plots_python'))
        z.write(delivery/'FULL_DELIVERY_MANIFEST.json',prefix/'FULL_DELIVERY_MANIFEST.json')
        z.writestr(str(prefix/'results/sumo_paper/full_study_status.json'),
            json.dumps(dict(status='complete',stage='finished',archived_copy=True,main_runs=450,extended_runs=240),indent=2)+'\n')
        z.writestr(str(prefix/'START_HERE.md'),
            '# Completed full-duration SUMO study\n\n'
            'Full main evaluation: 450 runs. Extended studies: 240 runs.\n'
            'Warmup/measurement: 600/3600 s; full model dimensions; 15 training episodes.\n'
            'Open matlab/RUN_FULL_SUMO_PLOTS.m in MATLAB to render the CSVs.\n'
            'Included PNG/PDF figures were rendered in Python, not MATLAB.\n'
            'See results/sumo_paper/audit/FULL_RESULTS_AUDIT.md and docs/FULL_DURATION_WORKFLOW.md.\n'
            'Regenerate large SUMO CSV traces using the source workflow; their checksums and inputs are included.\n')
    with zipfile.ZipFile(temporary) as z:
        if z.testzip() is not None:raise ValueError('Archive verification failed')
    os.replace(temporary,archive)
    matlab_archive=delivery/'SUMO_FULL_MATLAB_Code_and_CSVs.zip'
    with zipfile.ZipFile(matlab_archive,'w',zipfile.ZIP_DEFLATED) as z:
        prefix=Path('SUMO_FULL_MATLAB')
        for name in ('RUN_FULL_SUMO_PLOTS.m','render_sumo_results.m'):
            z.write(ROOT/'matlab'/name,prefix/'matlab'/name)
        for p in results.rglob('*'):
            if p.is_file() and p.suffix in ('.csv','.json','.md') and '.trained_model_cache' not in p.parts:
                z.write(p,prefix/'results/sumo_paper'/p.relative_to(results))
    shutil.copyfile(results/'audit/FULL_RESULTS_AUDIT.md',delivery/'FULL_RESULTS_AUDIT.md')
    print(json.dumps(dict(archive=str(archive),matlab_archive=str(matlab_archive)),indent=2))


if __name__=='__main__':main()
